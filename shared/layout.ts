/**
 * モバイル(<md)の左右ガター。20px / 430px 以上は 24px。
 *
 * 16px(`px-4`)だと、440pt 級の大きい端末で本文が 408px 幅になり、18px の太字タイトルが
 * 画面の端まで詰まって窮屈に見える。一方で小型端末(375pt)まで 24px にすると本文幅が
 * 削られて1行の文字数が減るため、画面幅で段を付ける:
 *
 * - 〜429px(iPhone SE/13 mini 等): 20px。絞り込みボトムシート(`FeedFilterSheet`)が
 *   以前から `px-5` なので、シートを開閉しても左端が動かない
 * - 430px 〜(iPhone 16 Pro Max 等の大型): 24px。md 以上(`md:px-6`)と同じ値になり、
 *   大型端末 → タブレットで段差が出ない
 *
 * この値は「1箇所で決める」必要がある: sticky ヘッダー(検索行・カテゴリタブ・チップ行)と
 * リスト本体でズレると、カードの上罫と検索バーの左端が揃わず歪んで見える。以前 `gap-y-10` を
 * 5ファイルに直書きしてリズムがずれた例があるため(`FEED_GAP_CLASS` のコメント参照)、
 * ガターも定数にしている。
 *
 * md 以上の値(`md:px-6` / `lg:px-8`)は各呼び出し側がそのまま付ける。画面ごとに最大幅と
 * サイドバーのオフセットが違い、ここで一律に決められないため。`min-[430px]` は Tailwind の
 * ブレークポイントより小さいので、`md:` / `lg:` の指定が後ろに来て正しく上書きされる。
 */
export const MOBILE_GUTTER_CLASS = 'px-5 min-[430px]:px-6';
